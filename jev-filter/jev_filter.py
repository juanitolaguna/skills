JEV_MODEL = "~typesafe/jev-latest"              # $0.042/M in, output free, 32k context
JEV_VERSION = "1"                               # Jev question set
DECISIONS_URL = "https://openrouter.ai/api/alpha/decisions"
KEY_FILE = ".openrouter_jev"

TEXT_EXT = {".md", ".markdown", ".txt", ".docx", ".pdf", ".epub", ".html", ".htm"}

# Criteria-independent questions: their answers describe the file, whatever is being looked for.
JEV_KIND = {
    "own_prose": "The owner's own connected prose: essay, article, blog post, chapter, speech, statement or letter, finished or a draft.",
    "notes": "Notes, fragments, bullet points, outlines, to-do or question lists, meeting minutes, journal stubs.",
    "reading_notes": "Excerpts, quotes or summaries of a book or paper, with little text of the owner's own.",
    "clipping": "A saved third-party article, paper, book or press release, or a translation of one.",
    "transcript": "A transcript of someone speaking, an interview, or a chat log.",
    "ai_generated": "A report or answer generated by an AI.",
    "admin": "Paperwork: forms, administrative letters, contact or reading lists.",
}


def jev_questions(criteria: str) -> dict:
    """The criteria become one yes/no question; a 'DROP:' part, if present, becomes its 'false' side."""
    keep, _, drop = criteria.strip().partition("DROP:")
    return {
        "matches": {"type": "noul", "instructions": "Does this document satisfy the selection criteria?",
                    "criteria": {"true": keep.strip(), "false": ("DROP: " + drop.strip()) if drop else "It does not satisfy them."}},
        "kind": {"type": "choice", "instructions": "What is this document?", "criteria": JEV_KIND},
        "own": {"type": "noul", "instructions": "Did the owner of this knowledge base write most of this text himself?",
                "criteria": {"true": "Most of the words are his own.",
                             "false": "Most of the words are quoted, clipped, translated, transcribed or generated."}},
    }


def jev_score(a: dict) -> float:
    """The criteria answer alone; mixing in `own` or `kind` dropped more but lost real texts. Calibrated on
    the Studies run (375 files, 109 known keeps): below 0.15 Jev dropped 55% and lost none; at 0.3 it lost
    3. The threshold moves with the criteria, so recalibrate when they change."""
    return a["matches"]


# ---------------------------------------------------------------- extraction

def _link(m: re.Match) -> str:
    label, url = m.group(1), m.group(2)
    hosts = re.findall(r"[a-z]+://([^/\s)]+)", url)   # archive.is/…/https://tsargrad.tv/… yields both
    # the domain stays: a link to tsargrad.tv or a day:// clip stamp says whose text this is
    return f"{label} (→ {' → '.join(hosts)})" if hosts else label


def _strip_md(text: str) -> str:
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", text)                       # images
    text = re.sub(r"data:[a-z/]+;base64,[A-Za-z0-9+/=]+", "", text)        # inline blobs
    text = re.sub(r"\[([^\]]*)\]\(((?:[^()]|\([^)]*\))*)\)", _link, text)  # links -> label <domain>
    text = re.sub(r"<[^>]{1,200}>", "", text)
    return re.sub(r"\n{3,}", "\n\n", text).strip()


def _strip_html(raw: str) -> str:
    raw = re.sub(r"(?is)<(script|style)[^>]*>.*?</\1>", "", raw)
    raw = re.sub(r"(?i)<br\s*/?>|</p>|</h\d>|</li>|</div>", "\n", raw)
    return re.sub(r"\n{3,}", "\n\n", html.unescape(re.sub(r"<[^>]+>", "", raw))).strip()


def _docx(path: Path) -> str:
    with zipfile.ZipFile(path) as z:
        xml = z.read("word/document.xml").decode("utf8", "ignore")
    paras = re.findall(r"<w:p[ >].*?</w:p>", xml, flags=re.S)
    return "\n\n".join(t for t in ("".join(re.findall(r"<w:t[^>]*>([^<]*)</w:t>", p)) for p in paras) if t.strip())


def _pdf(path: Path, max_pages: int | None = 6) -> tuple[str, int]:
    from pypdf import PdfReader
    logging.getLogger("pypdf").setLevel(logging.ERROR)
    reader = PdfReader(str(path))
    n = len(reader.pages)
    pick = range(n) if max_pages is None else sorted({*range(min(n, max_pages - 2)), n // 2, n - 1} & set(range(n)))
    parts = []
    for i in pick:
        try:
            parts.append(reader.pages[i].extract_text() or "")
        except Exception:
            pass
    return "\n\n[...]\n\n".join(p for p in parts if p.strip()), n


def _epub(path: Path, limit: int = 40000) -> str:
    out = []
    with zipfile.ZipFile(path) as z:
        for name in sorted(n for n in z.namelist() if n.endswith((".xhtml", ".html", ".htm"))):
            out.append(_strip_html(z.read(name).decode("utf8", "ignore")))
            if sum(map(len, out)) > limit:
                break
    return "\n\n".join(out)


def extract(path: Path) -> tuple[str, dict]:
    """Return (text, extra) for any supported file; text is '' when nothing is readable."""
    ext = path.suffix.lower()
    extra: dict = {}
    try:
        if ext in (".md", ".markdown"):
            text = _strip_md(path.read_text("utf8", "ignore"))
        elif ext == ".txt":
            text = path.read_text("utf8", "ignore")
        elif ext in (".html", ".htm"):
            text = _strip_html(path.read_text("utf8", "ignore"))
        elif ext == ".docx":
            text = _docx(path)
        elif ext == ".pdf":
            text, extra["pages"] = _pdf(path)
        elif ext == ".epub":
            text = _epub(path)
        else:
            text = ""
    except Exception as e:  # unreadable file: record it, never crash the run
        extra["error"] = f"{type(e).__name__}: {e}"[:200]
        text = ""
    return text, extra


# ---------------------------------------------------------------- features

SCRIPTS = {"latin": r"[A-Za-zÀ-ɏ]", "cyrillic": r"[Ѐ-ӿ]", "bengali": r"[ঀ-৿]",
           "arabic": r"[؀-ۿ]", "devanagari": r"[ऀ-ॿ]"}


def features(raw: str, text: str) -> dict:
    lines = [l for l in raw.splitlines() if l.strip()]
    nl = max(len(lines), 1)
    paras = [p for p in re.split(r"\n\s*\n", text) if p.strip()]
    prose_paras = [p for p in paras if len(p.split()) >= 40 and not re.match(r"\s*([-*>#]|\d+\.)", p)]
    letters = {k: len(re.findall(v, text[:20000])) for k, v in SCRIPTS.items()}
    tot = sum(letters.values()) or 1
    words = len(text.split())
    return {
        "words": words,
        "prose_paragraphs": len(prose_paras),
        "prose_word_share": round(sum(len(p.split()) for p in prose_paras) / max(words, 1), 2),
        "bullet_line_share": round(sum(bool(re.match(r"\s*([-*•]|\d+\.)\s", l)) for l in lines) / nl, 2),
        "checkbox_lines": sum(bool(re.match(r"\s*[-*] \[[ xX]\]", l)) for l in lines),
        "quote_line_share": round(sum(l.lstrip().startswith(">") for l in lines) / nl, 2),
        "urls": len(re.findall(r"https?://", raw)),
        "clip_header": bool(re.search(r"(?im)^>\s*\**(Author|Site|Saved|Source|Автор|Сайт|Сохранено|Источник)\b", raw[:1500])),
        "scripts": {k: round(v / tot, 2) for k, v in letters.items() if v / tot >= 0.05},
    }


def excerpt(text: str, budget: int) -> str:
    """Head-heavy sample: the head says what a text is, middle and tail say if it is developed and finished."""
    if len(text) <= budget:
        return text
    head = int(budget * 0.5)
    tail = int(budget * 0.15)
    n_mid = 3
    mid = (budget - head - tail) // n_mid
    span = len(text) - head - tail
    mids = [text[head + span * (i + 1) // (n_mid + 1):][:mid] for i in range(n_mid)]
    return "\n\n[...]\n\n".join([text[:head], *mids, text[-tail:]])


# ---------------------------------------------------------------- API

def find_key() -> str:
    for var in ("JEV_KEY", "OPENROUTER_API_KEY"):
        if os.environ.get(var):
            return os.environ[var].strip()
    for start in (Path.cwd(), Path(__file__).resolve().parent):
        for d in (start, *start.parents):
            if (d / KEY_FILE).is_file():
                return (d / KEY_FILE).read_text().strip()
    sys.exit(f"No key: set JEV_KEY or put {KEY_FILE} in the working directory or a parent.")


class Budget(Exception):
    pass


class JevClient:
    def __init__(self, key: str, budget_usd: float):
        self.key, self.budget = key, budget_usd
        self.spent, self.calls = 0.0, 0
        self.lock = threading.Lock()

    def decide(self, model: str, state: dict, questions: dict) -> dict:
        """One Jev call: typed questions in, probabilities out."""
        with self.lock:
            if self.spent >= self.budget:
                raise Budget(f"budget ${self.budget:.2f} reached")
        body = json.dumps({"model": model, "state": state, "questions": questions}).encode()
        last = None
        for attempt in range(6):
            t0 = time.perf_counter()
            try:
                req = urllib.request.Request(DECISIONS_URL, data=body, headers={
                    "Authorization": f"Bearer {self.key}", "Content-Type": "application/json", "X-Title": "jev-filter"})
                with urllib.request.urlopen(req, timeout=120) as r:
                    resp = json.load(r)
                a = resp["answers"]
                cost = float((resp.get("usage") or {}).get("cost") or 0)
                with self.lock:
                    self.spent += cost
                    self.calls += 1
                out = {"matches": a["matches"]["noul"], "own": a["own"]["noul"],
                       "kind": a["kind"]["choice"], "kind_p": a["kind"].get("probabilities", {}),
                       "kind_confidence": a["kind"].get("confidence"),
                       "jev_model": resp.get("model"), "_cost": cost,
                       "_latency_s": round(time.perf_counter() - t0, 3),
                       "_input_tokens": (resp.get("usage") or {}).get("input_tokens"),
                       "_state_chars": len(state.get("excerpt", ""))}
                out["match"] = jev_score(out)
                return out
            except urllib.error.HTTPError as e:
                last = f"HTTP {e.code}: {e.read()[:300]!r}"
                if e.code in (400, 401, 403, 413):
                    break
                retry_after = e.headers.get("Retry-After")
                if retry_after and retry_after.isdigit():
                    time.sleep(int(retry_after))
                    continue
            except Exception as e:
                last = f"{type(e).__name__}: {e}"[:300]
            time.sleep(min(30, 2 ** attempt) + random.random())
        raise RuntimeError(last)


class Cache:
    def __init__(self, path: Path):
        self.path, self.lock, self.data = path, threading.Lock(), {}
        if path.exists():
            for line in path.read_text().splitlines():
                try:
                    rec = json.loads(line)
                    self.data[rec["k"]] = rec["v"]
                except Exception:
                    pass

    @staticmethod
    def key(*parts: str) -> str:
        return hashlib.sha256("\x1f".join(parts).encode()).hexdigest()[:32]

    def get(self, k):
        return self.data.get(k)

    def put(self, k, v):
        with self.lock:
            self.data[k] = v
            with self.path.open("a") as f:
                f.write(json.dumps({"k": k, "v": v}, ensure_ascii=False) + "\n")


# ---------------------------------------------------------------- pipeline

@dataclass
class Doc:
    rel: str
    ext: str
    sha: str = ""
    feats: dict = field(default_factory=dict)
    extra: dict = field(default_factory=dict)
    text: str = field(default="", repr=False)
    stage: str = ""          # local | jev | judge | override (+cache)
    decision: str = ""       # keep | drop | error
    why: str = ""
    verdict: dict = field(default_factory=dict)


def discover(root: Path, include: list[str], exclude: list[str]) -> list[Path]:
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for fn in sorted(filenames):
            p = Path(dirpath) / fn
            rel = p.relative_to(root).as_posix()
            if p.suffix.lower() not in TEXT_EXT or fn.startswith("."):
                continue
            if include and not any(Path(rel).match(g) or rel.startswith(g.rstrip("*")) for g in include):
                continue
            if any(Path(rel).match(g) or rel.startswith(g.rstrip("*")) for g in exclude):
                continue
            out.append(p)
    return out


def jev_state(d: Doc, budget: int) -> dict:
    f = dict(d.feats)
    if d.extra.get("pages"):
        f["pdf_pages"] = d.extra["pages"]
    state = {"path": d.rel, "features": f, "excerpt": excerpt(d.text, budget)}
    if ".assets/" in d.rel:
        state["note"] = "attachment stored next to a note, often downloaded material"
    return state


def jev_filter(criteria: str, root: Path, out: Path, *,
               jev_model: str = JEV_MODEL,
               min_words: int = 80, keep_at: float = 0.9, drop_at: float = 0.15,
               jev_chars: int = 12000, batch_words: int = 20000, batch_files: int = 15,
               include: list[str] | None = None, exclude: list[str] | None = None,
               limit: int | None = None, sample: int | None = None,
               drop_clips: bool = True, trust_jev: bool = False, overrides: Path | None = None,
               budget_usd: float = 0.5, workers: int = 8, dry_run: bool = False, fresh_jev: bool = False,
               copy_selected: bool = True, log=None) -> list[Doc]:
    """Sort every readable document under `root` by `criteria`; write verdicts, a report, the judge queue
    and the kept texts to `out`. Run again after the judge has written its verdicts."""
    log = log or (lambda *a: print(*a, flush=True))
    root, out = root.expanduser().resolve(), out.expanduser().resolve()
    out.mkdir(parents=True, exist_ok=True)
    crit_hash = hashlib.sha256(criteria.strip().encode()).hexdigest()[:12]

    paths = discover(root, include or [], exclude or [])
    if sample:
        paths = random.Random(7).sample(paths, min(sample, len(paths)))
    if limit:
        paths = paths[:limit]
    log(f"[0] {len(paths)} candidate files under {root}")

    docs: list[Doc] = []
    seen: dict[str, Doc] = {}
    for p in paths:
        rel = p.relative_to(root).as_posix()
        d = Doc(rel=rel, ext=p.suffix.lower())
        d.text, d.extra = extract(p)
        raw = p.read_text("utf8", "ignore") if d.ext in (".md", ".txt", ".markdown") else d.text
        d.feats = features(raw, d.text)
        d.sha = hashlib.sha256(d.text.encode()).hexdigest()
        docs.append(d)
        if d.extra.get("error"):
            d.stage, d.decision, d.why = "local", "error", d.extra["error"]
        elif d.feats["words"] < min_words:
            d.stage, d.decision, d.why = "local", "drop", f"too short ({d.feats['words']} words < {min_words})"
        elif drop_clips and d.feats["clip_header"]:
            d.stage, d.decision, d.why = "local", "drop", "web clip (Site/Author/Saved header)"
        elif d.sha in seen:
            d.stage, d.decision, d.why = "local", "dup", f"duplicate of {seen[d.sha].rel}"
        else:
            seen[d.sha] = d
    todo = [d for d in docs if not d.decision]
    # measured on the Studies run: 1.84 chars per Jev input token (mixed Cyrillic/Latin), plus ~150 for the questions
    jev_tok = int(sum(len(excerpt(d.text, jev_chars)) for d in todo) / 1.84) + 150 * len(todo)
    log(f"[0] local: {len(docs) - len(todo)} settled for free, {len(todo)} go to Jev "
        f"(~{jev_tok // 1000}k tokens, ~${jev_tok * 0.042e-6:.3f} if nothing is cached)")
    if dry_run:
        _write_outputs(docs, out, criteria, None, copy_selected=False, root=root)
        return docs

    # ---- stage 1: Jev
    api = JevClient(find_key(), budget_usd)
    cache = Cache(out / ".jev_cache.jsonl")
    questions = jev_questions(criteria)

    def ask_jev(d: Doc) -> tuple[dict, bool]:
        k = Cache.key(JEV_VERSION, jev_model, crit_hash, d.sha, str(jev_chars))
        hit = None if fresh_jev else cache.get(k)
        if hit:
            return hit, True
        v = api.decide(jev_model, jev_state(d, jev_chars), questions)
        cache.put(k, v)
        return v, False

    log(f"[1] Jev ({jev_model}) on {len(todo)} files")
    t_stage = time.perf_counter()
    answers: list[tuple[Doc, dict, bool]] = []
    done = 0
    with ThreadPoolExecutor(workers) as ex:
        futs = {ex.submit(ask_jev, d): d for d in todo}
        for fut in as_completed(futs):
            d = futs[fut]
            try:
                v, cached = fut.result()
                answers.append((d, v, cached))
                score = jev_score(v)  # the score formula may change; the cached answers do not
                d.verdict = {"jev_score": score, "jev": {k: v[k] for k in ("matches", "own", "kind", "kind_p")},
                             "kind": v["kind"], "_cost": v.get("_cost", 0)}
                d.stage = "jev" + ("+cache" if cached else "")
                d.decision = "drop" if score < drop_at else "keep" if trust_jev and score >= keep_at else ""
                d.why = f"Jev: kind {v['kind']}, match {v['matches']:.2f}, own {v['own']:.2f}"
            except Exception as e:
                d.stage, d.decision, d.why = "jev", "error", str(e)[:300]
            done += 1
            if done % 50 == 0 or done == len(todo):
                log(f"    jev: {done}/{len(todo)}  spent ${api.spent:.4f}")
    stats = jev_stats(answers, time.perf_counter() - t_stage, workers, drop_at)
    prior = out / "jev_stats.json"
    if stats["fresh_calls"] == 0 and prior.exists():  # all from cache: the timing worth showing is the last fresh one
        last = json.loads(prior.read_text())
        if last.get("fresh_calls"):
            stats = {**last, "summary": last["summary"].split(" [")[0] + " [timed on the last fresh run; this run answered from cache]"}
    prior.write_text(json.dumps(stats, indent=1) + "\n")
    log("    " + stats["summary"])
    survivors = [d for d in todo if d.decision == ""]
    log(f"[1] Jev: dropped {sum(d.decision == 'drop' for d in todo)}, "
        f"kept unread {sum(d.decision == 'keep' for d in todo)}, {len(survivors)} go to the judge")

    # ---- stage 2: Claude as judge, through files
    jdir = out / "judge" / crit_hash
    jdir.mkdir(parents=True, exist_ok=True)
    (jdir / "criteria.txt").write_text(criteria.strip() + "\n")
    verdicts = read_judgements(jdir, log)
    pending = []
    for d in survivors:
        j = verdicts.get(d.sha)
        if j:
            d.verdict.update({k: j[k] for k in ("kind", "authorship", "finished", "languages") if k in j})
            d.verdict["judge"] = j["decision"]
            d.verdict["judge_sure"] = j.get("sure", True)
            d.stage, d.decision, d.why = "judge", j["decision"], j.get("reason", "")
        else:
            pending.append(d)
            d.stage, d.decision, d.why = "judge", "pending", "waiting for the judge"
    queues = write_queue(pending, jdir, root, batch_words, batch_files)
    log(f"[2] judge: {len(survivors) - len(pending)} verdicts read back, {len(pending)} pending"
        + (f" in {len(queues)} queue files: {jdir}/queue_*.jsonl" if queues else ""))

    apply_overrides(docs, overrides or out / "overrides.txt", log)
    _write_outputs(docs, out, criteria, api, copy_selected=copy_selected, root=root, stats=stats)
    kept = sum(d.decision == "keep" for d in docs)
    log(f"done: {kept} kept, {len(pending)} pending of {len(docs)}; {api.calls} Jev calls, ${api.spent:.4f}; see {out}/report.md")
    return docs


def jev_stats(answers: list[tuple[Doc, dict, bool]], wall_s: float, workers: int, drop_at: float) -> dict:
    """How long Jev took to decide, on how many documents, on how much data. Wall time is this run's
    (cache hits cost ~0 s); latency and tokens come from each call, cached ones included."""
    def pct(xs: list[float], q: float) -> float | None:
        xs = sorted(xs)
        return round(xs[min(len(xs) - 1, int(q * len(xs)))], 2) if xs else None
    fresh = [v for _, v, c in answers if not c]
    lat = [v["_latency_s"] for _, v, _ in answers if v.get("_latency_s") is not None]
    tok = [v.get("_input_tokens") or round(v.get("_cost", 0) / 0.042e-6) for _, v, _ in answers]
    words = sum(d.feats["words"] for d, _, _ in answers)
    chars = sum(v.get("_state_chars") or 0 for _, v, _ in answers)
    dropped = sum(jev_score(v) < drop_at for _, v, _ in answers)
    st = {
        "documents": len(answers), "fresh_calls": len(fresh), "cached": len(answers) - len(fresh),
        "dropped": dropped, "dropped_share": round(dropped / max(len(answers), 1), 3), "drop_at": drop_at,
        "wall_seconds": round(wall_s, 1), "workers": workers,
        "docs_per_second": round(len(fresh) / wall_s, 2) if fresh and wall_s else None,
        "latency_s": {"n": len(lat), "median": pct(lat, 0.5), "p95": pct(lat, 0.95), "max": pct(lat, 1.0)},
        "input_tokens": sum(tok), "excerpt_chars": chars, "document_words": words,
        "cost_usd": round(sum(v.get("_cost", 0) for _, v, _ in answers), 4),
    }
    st["summary"] = (f"Jev decided {st['documents']} docs ({st['fresh_calls']} fresh, {st['cached']} cached) in {st['wall_seconds']} s"
                     f" with {workers} workers; dropped {dropped} ({st['dropped_share']:.0%}); read {st['input_tokens'] / 1000:.0f}k tokens"
                     f" of excerpts from {words / 1000:.0f}k words of documents; latency median {st['latency_s']['median']} s,"
                     f" p95 {st['latency_s']['p95']} s; ${st['cost_usd']:.4f}")
    return st


def read_judgements(jdir: Path, log) -> dict[str, dict]:
    """Verdicts the judge wrote, keyed by content hash: a file judged once stays judged until it changes."""
    out: dict[str, dict] = {}
    for f in sorted(jdir.glob("*.verdicts.jsonl")):
        for n, line in enumerate(f.read_text().splitlines(), 1):
            if not line.strip():
                continue
            try:
                j = json.loads(line)
                assert j["decision"] in ("keep", "drop") and j["sha"]
            except Exception:
                log(f"    bad verdict line {f.name}:{n}: {line[:120]}")
                continue
            out[j["sha"]] = j
    return out


def write_queue(pending: list[Doc], jdir: Path, root: Path, batch_words: int, batch_files: int) -> list[Path]:
    """Split the pending files into batches of similar reading load; one subagent judges one batch."""
    for old in jdir.glob("queue_*.jsonl"):
        if re.fullmatch(r"queue_\d+\.jsonl", old.name):  # never the judge's queue_NN.verdicts.jsonl
            old.unlink()
    texts = jdir / "text"
    batches: list[list[dict]] = [[]]
    load = 0
    for d in sorted(pending, key=lambda d: d.rel):
        if d.ext in (".md", ".markdown", ".txt"):
            path = root / d.rel
        else:  # PDF, DOCX, EPUB: the judge reads the extracted text
            texts.mkdir(exist_ok=True)
            path = texts / f"{d.sha[:16]}.md"
            path.write_text(d.text)
        item = {"sha": d.sha, "rel": d.rel, "path": str(path), "words": d.feats["words"],
                "jev": {k: round(v, 2) if isinstance(v, float) else v for k, v in d.verdict["jev"].items() if k != "kind_p"}}
        if batches[-1] and (load + d.feats["words"] > batch_words or len(batches[-1]) >= batch_files):
            batches.append([])
            load = 0
        batches[-1].append(item)
        load += d.feats["words"]
    paths = []
    for i, b in enumerate(x for x in batches if x):
        q = jdir / f"queue_{i + 1:02d}.jsonl"
        q.write_text("".join(json.dumps(it, ensure_ascii=False) + "\n" for it in b))
        paths.append(q)
    return paths


def apply_overrides(docs: list[Doc], path: Path, log) -> None:
    """Human decisions win and survive reruns: lines '+ rel/path' keep, '- rel/path' drop, '#' comments."""
    if not path.exists():
        return
    by_rel = {d.rel: d for d in docs}
    for line in path.read_text().splitlines():
        line = line.split("  #")[0].strip()
        if len(line) < 3 or line[0] not in "+-":
            continue
        d = by_rel.get(line[1:].strip())
        if d is None:
            log(f"    override: no such file {line[1:].strip()!r}")
            continue
        d.decision, d.stage = ("keep" if line[0] == "+" else "drop"), "override"
        d.why = "human override"
        d.verdict["override"] = d.decision


