"""JEV filter: sort a large pile of documents by a plain-language criterion.

Three stages, cheapest first, so the expensive reader only sees what survives:

  0. local    extract text, measure it, drop what is empty, a duplicate or a web clip (free)
  1. jev      Jev, TypeSafe's decision model (OpenRouter Decisions API), answers typed
              questions about an excerpt and returns probabilities; the least probable
              documents are dropped here. The only paid stage: input tokens, no output.
  2. judge    Claude Code, outside this script: every survivor is written to a queue file
              under OUT/judge/<criteria-hash>/; subagents read the files, follow judge.md
              and write a verdicts file next to each queue; the next run reads them back.

Every cache is keyed by what its reader read: Jev answers by the state Jev was sent (with model,
criteria and question version), judge verdicts by the text the judge read (and criteria), so a rerun
pays only for what is new, and an extraction fix re-asks only what it changed.

Python:   jev_filter(criteria="...", root=Path(...), out=Path(...))
CLI:      jev_filter.py ROOT --criteria "..." --out DIR [--dry-run] [--limit N]
"""
